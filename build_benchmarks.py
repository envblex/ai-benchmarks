def generate():
    os.makedirs(BASE_DIR, exist_ok=True)
    with open(os.path.join(BASE_DIR, "README.md"), "w", encoding="utf-8") as f:
        f.write(README_ROOT)

    for version_name, categories in [("v1", V1_CATEGORIES), ("v2", V2_CATEGORIES)]:
        v_dir = os.path.join(BASE_DIR, version_name)
        os.makedirs(v_dir, exist_ok=True)

        v_readme = f"# AI実務エンジニアリング・ベンチマーク {version_name.upper()}\n\n"
        v_readme += f"全25問（5カテゴリ × 各5問）、各問20点・計500点満点の評価セットです。\n\n"
        v_readme += "## カテゴリ一覧\n\n"

        for cat_dir_name, cat_data in categories.items():
            cat_dir_path = os.path.join(v_dir, cat_dir_name)
            os.makedirs(cat_dir_path, exist_ok=True)

            v_readme += f"### [{cat_dir_name}: {cat_data['title']}](./{cat_dir_name}/)\n"
            v_readme += f"{cat_data['description']}\n\n"

            cat_readme = f"# {cat_data['title']}\n\n{cat_data['description']}\n\n## 問題一覧\n\n"

            for q in cat_data["questions"]:
                q_path = os.path.join(cat_dir_path, q["filename"])
                with open(q_path, "w", encoding="utf-8") as f:
                    f.write(q["content"])
                cat_readme += f"* [問{q['id']}：{q['title']}](./{q['filename']})\n"
                v_readme += f"  * [問{q['id']}：{q['title']}](./{cat_dir_name}/{q['filename']})\n"

            with open(os.path.join(cat_dir_path, "README.md"), "w", encoding="utf-8") as f:
                f.write(cat_readme)

            v_readme += "\n"

        with open(os.path.join(v_dir, "README.md"), "w", encoding="utf-8") as f:
            f.write(v_readme)

    print("Successfully generated all benchmark files in", BASE_DIR)

if __name__ == "__main__":
    generate()
